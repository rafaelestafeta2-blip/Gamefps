  public playFootstep(isSprinting = false, isCrouching = false): void {
    if (this.muted) return;
    const ctx = this.ensureContext();

    const volume = isCrouching ? 0.25 : isSprinting ? 0.68 : 0.46;
    const baseRate = isCrouching ? 0.86 : isSprinting ? 1.06 : 0.95;

    if (ctx && this.footstepRunBuffer) {
      const src = ctx.createBufferSource();
      src.buffer = this.footstepRunBuffer;
      src.playbackRate.setValueAtTime(
        baseRate + (Math.random() - 0.5) * 0.1,
        ctx.currentTime
      );
      const gain = ctx.createGain();
      gain.gain.setValueAtTime(volume, ctx.currentTime);
      src.connect(gain);
      gain.connect(ctx.destination);
      src.start();
      return;
    }

    if (this.footstepRunPool.length > 0) {
      const el = this.footstepRunPool[this.footstepRunPoolIdx];
      this.footstepRunPoolIdx =
        (this.footstepRunPoolIdx + 1) % this.footstepRunPool.length;
      el.currentTime = 0;
      el.volume = volume;
      el.playbackRate = baseRate;
      el.play().catch(() => {});
    }
  }

  public playPlantBombTutorial(): void {
    if (this.muted) return;
    try {
      if (!this.plantBombTutorialAudio) {
        this.plantBombTutorialAudio = new Audio(PLANT_BOMB_TUTORIAL_LOCAL_URL);
        this.plantBombTutorialAudio.preload = 'auto';
        this.plantBombTutorialAudio.volume = 1.0;
        this.plantBombTutorialAudio.onerror = () => {
          if (this.plantBombTutorialAudio) {
            this.plantBombTutorialAudio.src = PLANT_BOMB_TUTORIAL_GITHUB_RAW_URL;
            this.plantBombTutorialAudio.play().catch(() => {});
          }
        };
      }
      this.plantBombTutorialAudio.currentTime = 0;
      this.plantBombTutorialAudio.play().catch(() => {});
    } catch {
      // Audio autoplay policy fallback
    }
  }

  public stopPlantBombTutorial(): void {
    if (this.plantBombTutorialAudio) {
      try {
        this.plantBombTutorialAudio.pause();
        this.plantBombTutorialAudio.currentTime = 0;
      } catch {}
    }
  }
